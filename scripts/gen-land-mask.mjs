// Generates src/store/admin/landmask.js: a compact 0.5° equirectangular land / water bitmap (720 × 360, run-length
// encoded) used by the Analytics visitor globe to draw dot-matrix continents. Build-time only — the app has no runtime
// dependency on these packages.
//
// Source data: Natural Earth 1:50m land (public domain, naturalearthdata.com), as redistributed by the `world-atlas`
// npm package (ISC), decoded with `topojson-client` (ISC). Neither package is a project dependency; install them
// without saving, then run:
//   npm i --no-save world-atlas@2.0.2 topojson-client@3.1.0 && node scripts/gen-land-mask.mjs [path/to/node_modules]
import { createRequire } from 'node:module';
import { writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const mods = process.argv[2] ? resolve(process.argv[2]) : resolve(root, 'node_modules');
const require = createRequire(resolve(mods, 'x.js'));
const topo = require(resolve(mods, 'world-atlas/land-50m.json'));
const { feature } = require(resolve(mods, 'topojson-client'));

const W = 720, H = 360;
const land = feature(topo, topo.objects.land);
const rings = []; let offPrev = 0;
for (const f of land.features || [land]) {
  const g = f.geometry || f;
  const polys = g.type === 'Polygon' ? [g.coordinates] : g.type === 'MultiPolygon' ? g.coordinates : [];
  // Unwrap each ring so it is continuous across the antimeridian (Eurasia continues into Chukotka at lon > 180).
  for (const p of polys) for (const r of p) { let off = 0; rings.push(r.map(([x, y], i) => { if (i) { const d = x + off - (r[i - 1][0] + offPrev); if (d > 180) off -= 360; else if (d < -180) off += 360; } offPrev = off; return [x + off, y]; })); }
}
// Scanline even-odd fill at each row centre.
const bits = new Uint8Array(W * H);
for (let y = 0; y < H; y++) {
  const lat = 90 - (y + 0.5) * (180 / H), xs = [];
  for (const r of rings) for (let i = 0, n = r.length; i < n - 1; i++) {
    const [x1, y1] = r[i], [x2, y2] = r[i + 1];
    if ((y1 <= lat) !== (y2 <= lat)) xs.push(x1 + (lat - y1) / (y2 - y1) * (x2 - x1));
  }
  xs.sort((a, b) => a - b);
  for (let k = 0; k + 1 < xs.length; k += 2) {
    const a = Math.ceil((xs[k] + 180) * (W / 360) - 0.5), b = Math.floor((xs[k + 1] + 180) * (W / 360) - 0.5);
    for (let x = a; x <= b; x++) bits[y * W + ((x % W) + W) % W] = 1; // columns wrap around the globe
  }
}
// Run-length encode the whole bitmap row-major (alternating water / land runs, starting with water), as LEB128 varints.
const out = []; let cur = 0, run = 0;
const push = n => { do { let b = n & 127; n >>>= 7; if (n) b |= 128; out.push(b); } while (n); };
for (let i = 0; i < bits.length; i++) { if (bits[i] === cur) run++; else { push(run); cur = bits[i]; run = 1; } }
push(run);
const b64 = Buffer.from(out).toString('base64');
const landShare = bits.reduce((s, v) => s + v, 0) / bits.length;
const src = `// GENERATED by scripts/gen-land-mask.mjs — do not edit by hand.
// 0.5° equirectangular land mask (${W} × ${H}, row 0 = 90°N, column 0 = 180°W), run-length encoded as base64 LEB128 varints
// (alternating water / land runs, starting with water). Derived from Natural Earth 1:50m land (public domain) via the
// world-atlas package (ISC). Land share: ${(landShare * 100).toFixed(1)}%.
export const LAND_W = ${W}, LAND_H = ${H};
export const LAND_RLE = '${b64}';
`;
writeFileSync(resolve(root, 'src/store/admin/landmask.js'), src);
console.log('landmask.js written:', b64.length, 'base64 chars, land share', (landShare * 100).toFixed(1) + '%');
