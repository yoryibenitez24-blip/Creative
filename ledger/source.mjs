export const STATES = ['missing', 'partial', 'implemented-unverified', 'verified', 'blocked'];

// Scope decisions by the product owner. A deferred row stays `missing` (never `blocked`):
// nothing is waiting on it, and no UI may expose it until the decision is reversed.
export const isAiDependent = (r) => r.scope === 'ai' || /\bmodel\b/i.test(r.dependency) && !/non-AI/i.test(r.dependency);
// Rows that need a camera RAW decoder (licensed third-party or in-house). JPEG/PNG/TIFF development is unaffected.
export const RAW_DECODER_ROWS = new Set(['RAW-DECODE', 'RAW-CAMERA-MATRIX', 'RAW-METADATA', 'RAW-LEVELS', 'RAW-DEMOSAIC', 'RAW-HIGHLIGHTS', 'RAW-CAM-WB', 'RAW-COLOR-MATRIX', 'RAW-ORIENT', 'RAW-EMBEDDED-PREVIEW', 'DEV-DETAIL-DEMOSAIC-AWARE']);
export const isRawDecoderDependent = (r) => RAW_DECODER_ROWS.has(r.id);
export const DECISIONS = [
  { id: 'D-001', date: '2026-11-04', decision: 'No AI features yet. All model-dependent rows are deferred; non-AI alternatives are preferred where they exist (patch synthesis, user depth masks, classic denoise).', applies: isAiDependent },
  { id: 'D-002', date: '2026-11-04', decision: 'No RAW decoder license for now. Camera RAW/DNG decoding and RAW-only processing are deferred; Develop targets rendered images (JPEG/PNG/WebP and layers) with RAW-vs-rendered semantics kept in the design.', applies: isRawDecoderDependent },
];
export const isDeferred = (r) => DECISIONS.some(d => d.applies(r));

export function buildRows() {
  const rows = [];
  for (const [prefix, area, scope, milestone, reference, acceptance, items] of AREAS) {
    for (const [suffix, feature, behaviour, dependency = ''] of items) {
      const id = prefix + '-' + suffix;
      const [state = 'missing', evidence = '', note = ''] = STATUS[id] || [];
      const row = { id, area, scope, milestone, reference, feature, expected: behaviour || feature, state, dependency, acceptance, evidence, note };
      const deferred = DECISIONS.filter(d => d.applies(row)).map(d => `Deferred by ${d.id}`);
      if (deferred.length) row.note = [...deferred, note].filter(Boolean).join('; ');
      rows.push(row);
    }
  }
  return rows;
}

export const COLUMNS = ['id', 'area', 'scope', 'milestone', 'reference', 'feature', 'expected', 'state', 'dependency', 'acceptance', 'evidence', 'note'];
const esc = v => { const s = String(v ?? ''); return /[",\n]/.test(s) ? '"' + s.replace(/"/g, '""') + '"' : s; };
export function toCsv(rows) { return [`# Zertake capability ledger v${LEDGER_VERSION} (${LEDGER_DATE}). References: Photoshop = ${REFERENCES.photoshop}; Lightroom Classic = ${REFERENCES.lightroomClassic}.`, COLUMNS.join(','), ...rows.map(r => COLUMNS.map(c => esc(r[c])).join(','))].join('\n') + '\n'; }

export function summary(rows) {
  const by = (key) => { const m = {}; for (const r of rows) { m[r[key]] ??= Object.fromEntries(STATES.map(s => [s, 0])); m[r[key]][r.state]++; } return m; };
  const total = Object.fromEntries(STATES.map(s => [s, rows.filter(r => r.state === s).length]));
  const table = (m, label) => [`| ${label} | ${STATES.join(' | ')} | total |`, `|---|${STATES.map(() => '---:').join('|')}|---:|`, ...Object.entries(m).map(([k, v]) => `| ${k} | ${STATES.map(s => v[s]).join(' | ')} | ${STATES.reduce((a, s) => a + v[s], 0)} |`)].join('\n');
  return `# Capability ledger summary\n\nLedger v${LEDGER_VERSION}, ${LEDGER_DATE}. Generated by \`npm run ledger\` from \`ledger/source.mjs\`. Do not edit by hand.\n\nReferences: Photoshop: ${REFERENCES.photoshop}. Lightroom Classic: ${REFERENCES.lightroomClassic}. Docs accessed ${REFERENCES.docsAccessed}.\n\n**${rows.length} rows** · ${STATES.map(s => `${s}: ${total[s]}`).join(' · ')}\n\nZertake is **not** at Photoshop or Lightroom parity. ${total.verified} of ${rows.length} rows (${(100 * total.verified / rows.length).toFixed(1)}%) are verified.\n\n## Scope decisions\n\n${DECISIONS.map(d => `- **${d.id}** (${d.date}): ${d.decision} ${rows.filter(d.applies).length} rows are deferred under this decision (note column).`).join('\n')}\n\n## By scope\n\n${table(by('scope'), 'scope')}\n\n## By milestone\n\n${table(by('milestone'), 'milestone')}\n`;
}
