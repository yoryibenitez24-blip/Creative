// Regenerates the code the Edge Functions share with the storefront / admin, so the server computes exactly what the
// shopper's browser computed:
//   backend/supabase/functions/_shared/engine.js    ← commerceEngineSource() of src/store/commerce.js (discounts → shipping → tax)
//   backend/supabase/functions/_shared/services.js  ← bookingSlots / zonedDay / normalizeService from src/store/admin/services.js
//                                                     and src/store/serviceProduct.js (bundled with esbuild)
// Run after changing any of those files:  node backend/scripts/gen-engine.mjs
// (tests/backend.test.js fails when a generated file is out of date.)
import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';
import { commerceEngineSource } from '../../src/store/commerce.js';

const shared = f => fileURLToPath(new URL('../supabase/functions/_shared/' + f, import.meta.url));
export const ENGINE_PATH = shared('engine.js'), SERVICES_PATH = shared('services.js');

export function engineModule() {
  return `// @ts-self-types="./engine.d.ts"
// GENERATED by backend/scripts/gen-engine.mjs from src/store/commerce.js (commerceEngineSource) — do not edit by hand.
${commerceEngineSource()}export { CK };
`;
}

export async function servicesModule() {
  const r = await build({
    stdin: { contents: `export { bookingSlots, zonedDay } from './src/store/admin/services.js';\nexport { normalizeService, normalizeDigital } from './src/store/serviceProduct.js';\n`, resolveDir: fileURLToPath(new URL('../..', import.meta.url)), loader: 'js' },
    bundle: true, format: 'esm', platform: 'neutral', write: false, legalComments: 'none', logLevel: 'error',
  });
  return `// @ts-self-types="./services.d.ts"
// GENERATED by backend/scripts/gen-engine.mjs from src/store/admin/services.js + src/store/serviceProduct.js — do not edit by hand.
${r.outputFiles[0].text}`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  await writeFile(ENGINE_PATH, engineModule());
  await writeFile(SERVICES_PATH, await servicesModule());
  console.log('wrote', ENGINE_PATH, SERVICES_PATH);
}
